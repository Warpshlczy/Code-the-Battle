function phraseTranslate(text: string): string {
  let out = text;
  for (const [zh, en] of PHRASES) {
    if (!out.includes(zh)) continue;
    out = out.split(zh).join(en);
    if (!HAN.test(out)) return cleanup(out);
  }
  return cleanup(out);
}

function cleanup(text: string): string {
  return text
    .replace(/  +/g, ' ')
    .replace(/的\s*/g, ' ')
    .replace(/\s*的/g, ' ')
    .replace(/\s+([,.;:!?，。；：！？])/g, '$1')
    .replace(/（/g, '(')
    .replace(/）/g, ')')
    .replace(/：/g, ': ')
    .replace(/，/g, ', ')
    .replace(/。/g, '.')
    .replace(/、/g, ', ')
    .replace(/；/g, '; ')
    .replace(/！/g, '!')
    .replace(/？/g, '?')
    .replace(/\s+$/g, '')
    .trim();
}

function translate(text: string, depth = 0): string {
  if (!HAN.test(text)) return text;
  const exact = EXACT[text.trim()];
  if (exact) return exact;
  for (const rule of RULES) {
    const match = text.match(rule.re);
    if (match) return rule.en(match, (s) => translate(s, depth + 1));
  }
  if (depth > 3) return phraseTranslate(text);
  return phraseTranslate(text);
}

export function translateMessage(text: string | undefined, lang: Lang): string {
  if (!text) return '';
  return lang === 'zh' ? text : translate(text);
}

